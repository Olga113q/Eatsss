STRIP_WORDS = re.compile(
    r"\b(свеж\w*|молот\w*|рублен\w*|тертый|тертая|тертое|тертые|измельченн\w*|очищенн\w*|"
    r"мелк\w*|крупн\w*|охлажденн\w*|замороженн\w*|консервированн\w*|готов\w*|вареный|вареная|вареное|вареные)\b")


def clean(title):
    t = title.lower().replace("ё", "е")
    t = re.sub(r"[«»\"®™]", "", t)
    t = re.sub(r"\(.*?\)", " ", t)
    t = re.sub(r"\d+([.,]\d+)?\s*%[-–\w]*", " ", t)
    t = re.sub(r"\s+", " ", t).strip(" ,.-")
    return t


